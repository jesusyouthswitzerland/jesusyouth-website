/* ========================================
   LANGUAGE ENGINE
   ======================================== */
let currentLang = localStorage.getItem('jy-lang') || 'de';

function applyLanguage(lang) {
  const t = translations[lang];

  /* Plain-text elements */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  /* Elements that contain inner HTML (em, br, etc.) */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  /* Toggle button label: show the OTHER language */
  document.getElementById('langLabel').textContent = lang === 'de' ? 'EN' : 'DE';

  /* html lang attribute for accessibility */
  document.documentElement.lang = lang === 'de' ? 'de' : 'en';

  /* Persist */
  localStorage.setItem('jy-lang', lang);
  currentLang = lang;

  /* Keep show-more button in sync with current state */
  syncShowMoreLabel();
}

/* ========================================
   TOGGLE BUTTON
   ======================================== */
document.getElementById('langToggle').addEventListener('click', () => {
  applyLanguage(currentLang === 'de' ? 'en' : 'de');
});

/* ========================================
   STICKY NAV SHADOW
   ======================================== */
const nav = document.getElementById('nav');
