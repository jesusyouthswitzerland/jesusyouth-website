/* ========================================
   MOBILE HAMBURGER
   ======================================== */
const hamburger = document.getElementById('hamburger');
const navLinks  = document.getElementById('navLinks');

hamburger.addEventListener('click', () => {
  const open = navLinks.classList.toggle('active');
  hamburger.classList.toggle('active', open);
  hamburger.setAttribute('aria-expanded', open);
});

navLinks.querySelectorAll('a').forEach(link => {
  link.addEventListener('click', () => {
    navLinks.classList.remove('active');
    hamburger.classList.remove('active');
    hamburger.setAttribute('aria-expanded', 'false');
  });
});

/* ========================================
   FAQ ACCORDION
   ======================================== */
document.querySelectorAll('.faq__question').forEach(btn => {
  btn.addEventListener('click', () => {
    const item   = btn.closest('.faq__item');
    const isOpen = item.classList.contains('active');

    document.querySelectorAll('.faq__item').forEach(i => {
      i.classList.remove('active');
      i.querySelector('.faq__question').setAttribute('aria-expanded', 'false');
    });

    if (!isOpen) {
      item.classList.add('active');
      btn.setAttribute('aria-expanded', 'true');
    }
  });
});

/* ========================================
   SHOW MORE TESTIMONIALS
   ======================================== */
const showMoreBtn       = document.getElementById('showMoreBtn');
const extraTestimonials = document.querySelectorAll('.testimonials__extra');
let testimonialsShown   = false;

function syncShowMoreLabel() {
  if (!showMoreBtn) return;
  const t = translations[currentLang];
  showMoreBtn.textContent = testimonialsShown ? t['show.less'] : t['show.more'];
}

if (showMoreBtn) {
  showMoreBtn.addEventListener('click', () => {
    testimonialsShown = !testimonialsShown;
    extraTestimonials.forEach(t => {
      t.style.display = testimonialsShown ? 'block' : 'none';
    });
    syncShowMoreLabel();
  });
}

/* ========================================
   SMOOTH SCROLL
   ======================================== */
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', e => {
    const href   = anchor.getAttribute('href');
    if (href === '#') return;
    const target = document.querySelector(href);
    if (target) {
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  });
});

/* ========================================
   SCROLL-IN ANIMATIONS
   ======================================== */
const animatables = document.querySelectorAll(
  '.program-card, .event-card, .testimonial-card, .stat, .process__step'
);

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });

animatables.forEach(el => {
  el.classList.add('animate-on-scroll');
  observer.observe(el);
});

